package com.gk.rapido.model;

public class FareData {
	
	int ride_id;
	int peekHrsFare;
	int normalFare;
	public int getRide_id() {
		return ride_id;
	}
	public void setRide_id(int ride_id) {
		this.ride_id = ride_id;
	}
	public int getPeekHrsFare() {
		return peekHrsFare;
	}
	public void setPeekHrsFare(int peekHrsFare) {
		this.peekHrsFare = peekHrsFare;
	}
	public int getNormalFare() {
		return normalFare;
	}
	public void setNormalFare(int normalFare) {
		this.normalFare = normalFare;
	}

	
}
